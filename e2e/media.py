"""Media muxing checks against the real resident executable (Windows).

Generates small real-media fixtures with ffmpeg (a test-only tool; the
product never runs it), serves them as DASH and HLS from a local server,
seeds one media job per muxer into an isolated portable store, and lets the
real engine download and mux each one. For every output the run records the
state, size, SHA-256, the streams ffprobe sees and whether ffmpeg decodes it
without errors. A large synthetic dual-track download measures the
resident's peak memory, which must stay far below the size of the media.

  python e2e/media.py [--no-build] [--exe PATH] [--big-mib 1024]
                      [--compare e2e/results/media-<stamp>.json] [--label NAME]

--exe runs another build (for example the previous engine, to show a check
is not vacuous); --compare adds a check that every output is byte-identical
to the same scenario in an earlier run. Writes e2e/results/media-<stamp>.json
and exits non-zero if any check fails.
"""
